export const categories = ['All', ...new Set(articles.map(article => article.category))];

export function findArticles(category, search) {
  const query = search.toLocaleLowerCase('en').trim();
  return articles.filter(article =>
    (category === 'All' || article.category === category) &&
    (!query || [article.title, article.category, article.summary, ...article.sections.flat()].join(' ').toLocaleLowerCase('en').includes(query)));
}
